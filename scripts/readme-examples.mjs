#!/usr/bin/env node
// Turns every ```ts block in the README into one TypeScript file, so that
// `make consumer` compiles the examples exactly as a reader sees them. A
// README example with no check behind it is how sdk-rust shipped one naming
// a type that did not exist.
//
// Each block becomes the body of its own function, so blocks can reuse a name
// like `config`. Imports are hoisted out and merged, and `client` is
// declared up front, because later blocks carry on from the quickstart.
//
// Usage: readme-examples.mjs <README.md> <out.ts>

import { readFileSync, writeFileSync } from "node:fs";

const [readme, output] = process.argv.slice(2);
if (!readme || !output) {
  console.error("usage: readme-examples.mjs <README.md> <out.ts>");
  process.exit(2);
}

const blocks = [...readFileSync(readme, "utf8").matchAll(/^```ts\n([\s\S]*?)^```$/gm)].map(
  (match) => match[1],
);
if (blocks.length === 0) {
  console.error(`no \`\`\`ts blocks in ${readme}`);
  process.exit(1);
}

const IMPORT = /^import \{([^}]*)\} from "@incident-io\/sdk";\n/gm;
const imported = new Set(["IncidentsV2Api"]);
const bodies = blocks.map((block, index) => {
  const body = block.replace(IMPORT, (_, names) => {
    for (const name of names.split(",").map((name) => name.trim()).filter(Boolean)) imported.add(name);
    return "";
  });
  if (/^import /m.test(body)) {
    console.error(`block ${index + 1} imports something other than @incident-io/sdk`);
    process.exit(1);
  }
  return `export async function example${index + 1}() {\n${body}}\n`;
});

writeFileSync(
  output,
  `// Generated by scripts/readme-examples.mjs from the README. Do not edit.\n` +
    `import { ${[...imported].sort().join(", ")} } from "@incident-io/sdk";\n\n` +
    `declare const client: IncidentsV2Api;\n\n` +
    bodies.join("\n"),
);
console.log(`readme: ${blocks.length} examples`);
